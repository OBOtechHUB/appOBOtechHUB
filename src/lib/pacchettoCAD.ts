/** Testo del file LEGGIMI del pacchetto CAD (righe Windows). */
export function leggimiCAD(nome: string): string {
  return [
    "PROGETTAZIONE LPS - PACCHETTO PER AUTOCAD E ZWCAD",
    "",
    `Progetto e revisione: ${nome} (codice CRM, LPS, revisione; "_bozza" = revisione non ancora emessa)`,
    "",
    "Contenuto della cartella",
    `  ${nome}.dxf       tavole 2D: LPS-01 pianta coperture, LPS-02 prospetti con sfera rotolante,`,
    "                     LPS-03 calate e impianto di terra, LPS-04 particolari costruttivi",
    `  ${nome}_tavole.pdf le stesse tavole in PDF vettoriale, pronte da stampare`,
    `  ${nome}.ifc        modello BIM IFC4 (edificio, aste, conduttori, picchetti) per Revit, ArchiCAD, Solibri`,
    `  ${nome}.lpsdati   dati del progetto per il modello 3D e la distinta`,
    "  LPS.lsp            programma per AutoCAD e ZWCAD",
    "",
    "Come si usa (una sola volta per progetto)",
    "  1. Estrai tutta la cartella dallo ZIP (non aprire i file dentro lo ZIP).",
    `  2. Apri ${nome}.dxf con AutoCAD o ZWCAD (doppio clic o Apri).`,
    "  3. Trascina LPS.lsp dentro la finestra del disegno.",
    "     Se compare l'avviso di sicurezza scegli \"Carica una volta\" (AutoCAD) o \"Carica\" (ZWCAD).",
    "  4. Alla domanda \"Costruire il disegno LPS...\" premi Invio.",
    "     Il programma disegna il modello 3D accanto alla tavola con blocchi e codici OBO,",
    "     inserisce legenda, particolari costruttivi, distinta dei materiali, squadratura nel formato ISO adatto",
    "     (da A3 ad A0, scala 1:100, 1:200...) con il testalino OBO compilato, e salva il disegno in formato DWG nella stessa cartella",
    `     (${nome}.dwg; se esiste gia' non viene sovrascritto: si aggiunge un numero).`,
    "",
    "Blocchi OBO ufficiali (facoltativo)",
    "  Se nella cartella c'e' una sottocartella \"blocchi\" con i file <codice>.dwg, vengono usati quelli.",
    "  Altrimenti si usano i simboli standard LPS con lo stesso nome e gli attributi CODICE, DESCRIZIONE, TIPO.",
    "  La cartella dei blocchi si puo' indicare anche una volta per tutte con il comando LPS-BLOCCHI.",
    "",
    "Comandi disponibili dopo il caricamento (scrivi LPS per l'elenco):",
    "  LPS-AUTO, LPS-IMPORTA   costruiscono il disegno dal .lpsdati (con legenda, particolari, squadratura e testalino)",
    "  LPS-SQUADRA             ridisegna la squadratura scegliendo formato (A3...A0) e scala",
    "  LPS-SEPARAZIONE         verifica la distanza di separazione tra due punti (s = ki kc / km l)",
    "  LPS-PENETRAZIONE        penetrazione della sfera rotolante tra due punte (nei prospetti della TAV. LPS-02)",
    "  LPS-SFERA               disegna la sfera rotolante in un punto",
    "  LPS-NUMERA              numera le calate C1, C2... cliccando nell'ordine",
    "  LPS-DISTINTA, LPS-TABELLA  distinta dei materiali dal disegno (CSV e tabella nel disegno)",
    "  LPS-TESTALINO           testalino OBO (committente, opera, revisioni, progettista, tavola) sul layer LPS-CART",
    "  LPS-LEGENDA             legenda dei layer predefiniti sul layer LPS-LEGE",
    "  LPS-ESPORTA             esporta i contorni dell'edificio verso il sito",
    "  LPS-BLOCCHI             cartella dei blocchi OBO ufficiali",
    "",
    "Stampa: ogni tavola si stampa dallo spazio modello con finestra sulla sua squadratura (le tavole sono una sotto",
    "l'altra); il modello 3D e' a destra della prima tavola e non va stampato. Oppure stampa direttamente il PDF.",
    "",
  ].join("\r\n");
}
